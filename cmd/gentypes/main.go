// Command gentypes writes the TypeScript types for the JSON the API sends, from the Go
// structs that produce it, so the web client cannot drift from the server.
//
//	go run ./cmd/gentypes            # rewrites web/lib/types.gen.ts
//
// A test fails when the committed file is out of date.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"reflect"
	"strings"

	"github.com/bandhanpatel/lets-go-gaffer/internal/api"
	"github.com/bandhanpatel/lets-go-gaffer/internal/news"
	"github.com/bandhanpatel/lets-go-gaffer/internal/service"
	"github.com/bandhanpatel/lets-go-gaffer/internal/tsgen"
)

const defaultOut = "web/lib/types.gen.ts"

const header = `// Code generated by "go run ./cmd/gentypes" from the Go response types. DO NOT EDIT.
// The API never sends null for a list (internal/api/nonnil.go), so lists are typed T[].
// A pointer may be null, and a field marked omitempty may be absent.

`

// generate returns the contents of the types file.
func generate() (string, error) {
	g := &tsgen.Generator{ListsNeverNull: true, Name: func(t reflect.Type) string {
		// MyTeamView in Go is MyTeam in the client: "View" is how the Go side says "response".
		if t.PkgPath() != "" && strings.HasSuffix(t.Name(), "View") {
			return strings.TrimSuffix(t.Name(), "View")
		}
		return t.Name()
	}}
	for _, v := range []any{
		service.MyTeamView{}, service.LineupView{}, service.TransfersView{}, service.PlayersView{},
		service.NewsSearchView{}, service.StatusView{}, service.SquadView{}, service.BacktestView{}, service.WhatIfView{}, service.WhatIfRequest{}, service.SubsView{}, service.SubsRequest{}, service.ChipsView{}, service.OutlookView{},
		service.UserSettingsView{}, service.UserSettingsRequest{},
		service.AlertsView{}, service.WatchlistView{}, service.HealthView{},
		api.AskDone{}, api.ErrorBody{}, news.RefreshStatus{},
	} {
		if err := g.Add(v); err != nil {
			return "", err
		}
	}
	var buf bytes.Buffer
	buf.WriteString(header)
	if err := g.Write(&buf); err != nil {
		return "", err
	}
	return buf.String(), nil
}

func main() {
	out := flag.String("o", defaultOut, "file to write")
	flag.Parse()
	text, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, []byte(text), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("wrote", *out)
}
